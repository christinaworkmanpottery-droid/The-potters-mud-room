  db.prepare('INSERT INTO pieces (id,user_id,title) VALUES (?,?,?)').run('blue','a','Blue bowl');
  db.prepare('INSERT INTO glazes (id,user_id,name) VALUES (?,?,?)').run('ocean','a','Ocean');
